def canon_of(naver_name):
    if any(k in naver_name for k in IGNORE):
        return None
    for key, canon in RULES:
        if key in naver_name:
            return canon
    return None


class Ref:
    def __init__(self, path=None):
        path = path or os.path.join(ROOT, "data", "ref", "naver_themes.json")
        d = json.load(open(path, encoding="utf-8"))
        self.by_code, self.by_name, self.desc = {}, {}, {}
        n_total = max(len(d["names"]), 1)
        for tname, t in d["themes"].items():
            canon = canon_of(tname)
            if not canon:
                continue
            w = math.log(n_total / max(len(t["codes"]), 1))
            for c in t["codes"]:
                self.by_code.setdefault(c, {})
                self.by_code[c][canon] = max(self.by_code[c].get(canon, 0), w)
                r = d["reasons"].get(f"{t['no']}:{c}")
                if r and (c, canon) not in self.desc:
                    self.desc[(c, canon)] = r
        for c, n in d["names"].items():
            self.by_name[n] = c

    def canons(self, code=None, name=None):
        code = code or self.by_name.get(name)
        return self.by_code.get(code, {}) if code else {}

    def describe(self, code, canon, limit=48):
        r = self.desc.get((code, canon), "")
        r = re.split(r"(?<=[.。])\s|\n", r.strip())[0].rstrip(".")
        r = re.sub(r"\s+", " ", r)
        return r if len(r) <= limit else r[:limit].rstrip() + "…"
